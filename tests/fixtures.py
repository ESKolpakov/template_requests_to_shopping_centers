"""Синтетические тестовые данные.

Важно: здесь НЕТ реальных персональных данных и НЕТ содержимого настоящего
бланка ГБУ «МКМЦН» — шаблон письма для тестов собирается программно (см.
`build_synthetic_template`), со случайными вымышленными названиями
организаций и текстом-заглушкой, только чтобы проверить механику заполнения
плейсхолдеров и таблицы (см. docx_template.py). Реальный шаблон
пользователь загружает сам через раздел «Шаблоны» приложения.
"""

from __future__ import annotations

import openpyxl
from docx import Document
from docx.oxml.ns import qn


def build_synthetic_template(path: str) -> None:
    """Собрать минимальный, но структурно похожий на образцы шаблон:
    invisible-таблица с адресным блоком, тело письма с плейсхолдерами,
    таблица объектов торговли со строкой-образцом."""
    doc = Document()

    # "Невидимая" двухколоночная таблица адресного блока (как в образцах).
    header_tbl = doc.add_table(rows=1, cols=2)
    header_tbl.autofit = True
    header_tbl.cell(0, 0).text = "ТЕСТОВЫЙ ЗАГОЛОВОК ОРГАНИЗАЦИИ (ЗАГЛУШКА)"
    header_tbl.cell(0, 1).paragraphs[0].add_run("{{RECIPIENT_BLOCK}}")

    doc.add_paragraph("Об оказании содействия (тестовый шаблон)")
    doc.add_paragraph("{{GREETING}}")
    doc.add_paragraph(
        "Тестовый текст: торговый центр «{{TC_NAME}}», расположенный по "
        "адресу: {{TC_ADDRESS}}, {{VERB_OSUSHESTVLYAL}} {{SUBJECT_WORD_FORM}}."
    )
    doc.add_paragraph("Просьба предоставить сведения в срок до {{DEADLINE_DATE}}.")
    doc.add_paragraph("Подписант: {{SIGNATORY_NAME}}")
    doc.add_paragraph("{{EXECUTOR_NAME}}")
    doc.add_paragraph("{{EXECUTOR_PHONE}}")

    obj_tbl = doc.add_table(rows=2, cols=10)
    headers = [
        "№ п/п", "Наименование объекта", "Хозяйствующий субъект", "ИНН",
        "Адрес", "Этаж", "Помещение", "Дата сбора информации", "ID",
        "Отметка",
    ]
    for i, h in enumerate(headers):
        obj_tbl.cell(0, i).text = h
    tokens = [
        "{{ROW.NUM}}", "{{ROW.NAME}}", "{{ROW.SUBJECT}}", "{{ROW.INN}}",
        "{{ROW.ADDRESS}}", "{{ROW.FLOOR}}", "{{ROW.ROOM}}", "{{ROW.DATE}}",
        "{{ROW.ID}}", "",
    ]
    for i, tok in enumerate(tokens):
        obj_tbl.cell(1, i).text = tok

    doc.save(path)


