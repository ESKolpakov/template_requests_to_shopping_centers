def test_parse_egrul_text_basic_fields():
    data = parse_egrul_text(SAMPLE_TEXT)
    assert data.inn == "7700000001"
    assert data.full_name == 'ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "ТЕСТОВАЯ КОМПАНИЯ"'
    assert data.short_name == 'ООО "ТЕСТОВАЯ КОМПАНИЯ"'
    assert data.legal_address == "123456, Г.МОСКВА, УЛ. ТЕСТОВАЯ, Д. 1"


def test_parse_egrul_text_representative_person():
    data = parse_egrul_text(SAMPLE_TEXT)
    assert data.representative_surname == "ТЕСТОВА"
    assert data.representative_first_name == "ЕКАТЕРИНА"
    assert data.representative_patronymic == "ПЕТРОВНА"
    assert data.representative_position == "ГЕНЕРАЛЬНЫЙ ДИРЕКТОР"
    assert data.representative_gender == "female"
    assert data.representative_is_organization is False


def test_parse_egrul_text_representative_organization():
    data = parse_egrul_text(SAMPLE_TEXT_ORG_REPRESENTATIVE)
    assert data.representative_surname is None
    assert data.representative_org_name is not None
    assert "УПРАВЛЯЮЩАЯ КОМПАНИЯ" in data.representative_org_name
    assert data.representative_is_organization is True
